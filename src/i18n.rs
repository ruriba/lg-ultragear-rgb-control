//! UI translations. A flat struct of static strings per language: adding a
//! field breaks the build until every language fills it, so no key can be
//! silently missing. `init` fixes the process language once at startup (from
//! the saved setting, falling back to the Windows UI language); `t()` reads it
//! anywhere afterwards.

use std::sync::OnceLock;
use windows::Win32::Globalization::GetUserDefaultUILanguage;

/// Languages offered in the menu. `System` follows the Windows UI language.
#[derive(Clone, Copy, PartialEq, Eq, Debug, serde::Serialize, serde::Deserialize)]
pub enum Language {
    System,
    En,
    Es,
    Fr,
    De,
    Pt,
    It,
    Ru,
    Ja,
    Zh,
    Ko,
}

/// The Windows UI language, mapped to one of ours (primary LANGID).
pub fn system_language() -> Language {
    let primary = unsafe { GetUserDefaultUILanguage() } & 0xFF;
    match primary {
        0x0A => Language::Es,
        0x0C => Language::Fr,
        0x07 => Language::De,
        0x16 => Language::Pt,
        0x10 => Language::It,
        0x19 => Language::Ru,
        0x11 => Language::Ja,
        0x04 => Language::Zh,
        0x12 => Language::Ko,
        _ => Language::En,
    }
}

fn resolve(language: Language) -> &'static Lang {
    match language {
        Language::En => &EN,
        Language::Es => &ES,
        Language::Fr => &FR,
        Language::De => &DE,
        Language::Pt => &PT,
        Language::It => &IT,
        Language::Ru => &RU,
        Language::Ja => &JA,
        Language::Zh => &ZH,
        Language::Ko => &KO,
        Language::System => resolve(system_language()),
    }
}

static LANG: OnceLock<&'static Lang> = OnceLock::new();

/// Fixes the UI language for this process. Call once at startup, before any
/// menu string is built; later calls are ignored.
pub fn init(language: Language) {
    let _ = LANG.set(resolve(language));
}

/// The process UI language.
pub fn t() -> &'static Lang {
    LANG.get().copied().unwrap_or(&EN)
}

